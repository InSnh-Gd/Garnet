"""Extract and run the real Darwin host-composite BO path under ASan/UBSan.

Usage: python3 mesa-patches/test-host-composite.py PATCHED_MESA OUTPUT_DIR
"""
import importlib.util
import os
import re
import shlex
import subprocess
import sys
from pathlib import Path

BO_TARGETS = [
    "radv_amdgpu_bo_va_size",
    "radv_amdgpu_bo_va_op",
    "radv_amdgpu_host_child_from_ptr",
    "radv_amdgpu_host_composite_from_ptr",
    "radv_amdgpu_get_optimal_vm_alignment",
    "radv_amdgpu_winsys_bo_from_ptr",
    "radv_amdgpu_winsys_bo_destroy",
    "radv_amdgpu_winsys_bo_map",
    "radv_amdgpu_winsys_bo_unmap",
    "radv_amdgpu_winsys_get_fd",
]
CS_TARGETS = [
    "radv_amdgpu_cs_find_buffer",
    "radv_amdgpu_cs_add_buffer_internal",
    "radv_amdgpu_cs_add_buffer",
]
CONSTANTS = (
    "RADV_DARWIN_HOST_CHUNK",
    "RADV_DARWIN_HOST_CHILDREN",
)


def load_extract_helper():
    path = Path(__file__).resolve().parent / "test-composite-bo.py"
    spec = importlib.util.spec_from_file_location("composite_extract", path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot load extraction helper from {path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def source_constant(path, name):
    match = re.search(rf"^#define\s+{re.escape(name)}\s+([^\n]+)$",
                      path.read_text(), re.MULTILINE)
    if match is None:
        raise ValueError(f"source constant not found: {name}")
    return match.group(1).strip()


def main():
    if len(sys.argv) != 3:
        print("usage: python3 mesa-patches/test-host-composite.py PATCHED_MESA OUTPUT_DIR")
        return 2

    mesa = Path(sys.argv[1]).resolve()
    out = Path(sys.argv[2]).resolve()
    out.mkdir(parents=True, exist_ok=True)

    bo_c = mesa / "src/amd/vulkan/winsys/amdgpu/radv_amdgpu_bo.c"
    cs_c = mesa / "src/amd/vulkan/winsys/amdgpu/radv_amdgpu_cs.c"
    for path in (bo_c, cs_c):
        if not path.is_file():
            print(f"missing production source: {path}")
            return 2

    helper = load_extract_helper()
    cc = shlex.split(os.environ.get("CC", "clang"))
    define = "-DHAVE_AMDGPU_DARWIN=1"
    bo_text = helper.preprocess(cc, bo_c, define)
    cs_text = helper.preprocess(cc, cs_c, define)

    parts = [
        "/* Auto-generated by test-host-composite.py from Mesa production source. */",
        f"/* BO source: {bo_c} ({len(bo_text)} bytes preprocessed) */",
        f"/* CS source: {cs_c} ({len(cs_text)} bytes preprocessed) */",
    ]
    for name in CONSTANTS:
        try:
            value = source_constant(bo_c, name)
        except ValueError as exc:
            print(exc)
            return 3
        parts.append(f"#define {name} {value}")

    order = [(bo_text, str(bo_c), name) for name in BO_TARGETS]
    order += [(cs_text, str(cs_c), name) for name in CS_TARGETS]
    for text, src, name in order:
        try:
            start, _end, body = helper.extract_function(text, name)
        except ValueError as exc:
            print(f"extraction failed: {exc}; refusing a stale host-composite test")
            return 3
        lineno = text.count("\n", 0, start) + 1
        parts.append(f"\n/* ---- {name} from {src} "
                     f"(preprocessed line {lineno}, {len(body)} bytes) ---- */")
        parts.append(body)

    inc = out / "host_composite_production.inc"
    inc.write_text("\n".join(parts) + "\n")
    print(f"extracted {len(order)} production functions -> {inc}")

    test_c = Path(__file__).resolve().parent / "host_composite_test.c"
    exe = out / "host-composite-test"
    cmd = cc + [
        "-std=gnu11", "-g", "-O1", "-fsanitize=address,undefined",
        "-fno-omit-frame-pointer", "-D_GNU_SOURCE", define,
        "-I", str(out), "-Wall", "-Wextra", "-Werror",
        "-Wno-unused-parameter", "-Wno-unused-variable",
        "-Wno-unused-but-set-variable",
        str(test_c), "-o", str(exe),
    ]
    print("+ " + " ".join(cmd), flush=True)
    subprocess.run(cmd, check=True)

    env = dict(os.environ)
    env["UBSAN_OPTIONS"] = "halt_on_error=1:print_stacktrace=1"
    if sys.platform == "darwin":
        env["ASAN_OPTIONS"] = "detect_leaks=0:halt_on_error=1"
    else:
        env["ASAN_OPTIONS"] = "detect_leaks=1:halt_on_error=1"
    print(f"+ {exe}", flush=True)
    proc = subprocess.run([str(exe)], env=env)
    if proc.returncode != 0:
        print(f"host-composite test FAILED (exit {proc.returncode})")
        return 1
    print("host-composite test PASSED")
    return 0


if __name__ == "__main__":
    sys.exit(main())
