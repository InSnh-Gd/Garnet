// aux 0.0.5 (G6, an internal design note "G6 design" section 2): slot 239 of the family (IOGraphicsAccelerator2::newUserClient). Type 'GRNT' is the bring-up kext's native client, attached to THIS accelerator so that a
// sandboxed application (whose profile admits user clients on an IOAccelerator service) can open it. It is decided HERE, before the family's per-PID client limits and its 0x9bc bookkeeping, and an 'GRNT' open NEVER reaches the
// family (the family would hand an unknown type to newContext and give the caller a generic IOAccelContext2): kill switch off, gate not passed, no usable hook = kIOReturnUnsupported. Every other type is the family's, untouched.
// The hook returns an IOReturn: it is compared with kIoSuccess (nuc_result), never read as a bool (vhook's "1 = handled" convention does not apply).
IOReturn GarnetAccelerator::newUserClient(task_t owningTask, void *securityID, UInt32 type, IOUserClient **handler) {
	GARNET_AUX_ENTER(type == GARNET_METAL_UC_GARNETN ? kIOReturnUnsupported : IOGraphicsAccelerator2::newUserClient(owningTask, securityID, type, handler));
	const NucPlan plan = nuc_plan(type, true, gGateState == 1, gOps, ctx != nullptr && ctx == gCtx);
	if (plan == kNucFamily) return IOGraphicsAccelerator2::newUserClient(owningTask, securityID, type, handler);
	if (handler) *handler = nullptr;
	if (plan != kNucNative) return kIOReturnUnsupported;
	if (!handler) return kIOReturnBadArgument;
	IOUserClient *uc = nullptr;
	const int32_t rc = gOps->native_open(ctx, this, (void *)owningTask, securityID, type, (void **)&uc);
	const int32_t out = nuc_result(rc, uc != nullptr);
	if (out == kIoSuccess) *handler = uc;
	else if (uc) { uc->release(); uc = nullptr; }   // a refusal never leaves an object behind (the hook returns none; this is belt and braces)
	garnet_trace(GARNET_TR_NATIVE_OPEN, (uint64_t)(uint32_t)out, (uint64_t)(uintptr_t)uc);
	return (IOReturn)out;
}
IOReturn GarnetAccelerator::newUserClient(task_t owningTask, void *securityID, UInt32 type, OSDictionary *properties, IOUserClient **handler) {
	GARNET_AUX_ENTER(type == GARNET_METAL_UC_GARNETN ? kIOReturnUnsupported : IOService::newUserClient(owningTask, securityID, type, properties, handler));
	// IOService's fallback discards failures from the four-argument hook.
	if (type == GARNET_METAL_UC_GARNETN) return newUserClient(owningTask, securityID, type, handler);
	return IOService::newUserClient(owningTask, securityID, type, properties, handler);
}
