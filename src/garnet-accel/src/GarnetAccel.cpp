// Slot 277 performTransaction(IOAccelDisplayPipeTransaction2*) (family symbol __ZN18IOAccelDisplayPipe18performTransactionEP30IOAccelDisplayPipeTransaction2, vtables/
// IOAccelDisplayPipe.tsv row 277; the argument list is that mangled name's). The generated header declares the slot as `void _vslot277()`, so the override is a
// naked tail jump: rdi (this) and rsi (the transaction) arrive untouched in garnet_dp_perform, which returns in rax what the family's caller reads (an IOReturn in
// eax; the base returns 0xE00002C7). Same trampoline contract as the generated ones: kill switch first, then the display hook, else the family's own slot.
extern "C" __attribute__((used, visibility("hidden"))) uint64_t garnet_dp_perform(GarnetDisplayPipe *self, IOAccelDisplayPipeTransaction2 *txn) {
	GARNET_AUX_ENTER((uint64_t)0);
	uint64_t a[6] = { (uint64_t)(uintptr_t)txn, 0, 0, 0, 0, 0 }; uint64_t r = 0;
	if (garnet_disp_vhook(GARNET_VC_DISPLAYPIPE, 277, (void *)self, a, 1, &r)) return r;
	return ((uint64_t (*)(GarnetDisplayPipe *, IOAccelDisplayPipeTransaction2 *))(garnet_ztvfam_IOAccelDisplayPipe[2 + 277]))(self, txn);
}
__attribute__((naked)) void GarnetDisplayPipe::_vslot277() { __asm__("jmp _garnet_dp_perform"); }

extern "C" kmod_info_t kmod_info;   // kmod_info.c (KMOD_EXPLICIT_DECL)
static uintptr_t garnet_anchor() { return (uintptr_t)&garnet_anchor; }

static bool garnet_layout_gate() {
	if (gGateState) return gGateState == 1;
	uintptr_t lo = 0, hi = 0;
	const bool kw = text_window(garnet_anchor(), (uintptr_t)kmod_info.address, (uintptr_t)kmod_info.size, &lo, &hi);   // our own image range (kmod_info), else +-4 MiB around a function of ours
	GARNET_LOG("layout window: %s [%#lx, %#lx)", kw ? "kmod_info" : "fallback", (unsigned long)lo, (unsigned long)hi);
	uint32_t total = 0, want = 0;
	bool ok = true;
	for (const ClassGate &g : kGate) {
		want += g.nslots;
		// class sizes: the family's registered metaclass must have the size the header was built for; ours is sizeof(our class)
		const OSSymbol *s = OSSymbol::withCString(g.fam);
		const OSMetaClass *fm = s ? OSMetaClass::getMetaClassWithName(s) : nullptr;
		if (s) s->release();
		if (!fm || !size_ok((uint32_t)fm->getClassSize(), g.famSize)) {
			GARNET_LOG("layout FAIL class %s: family size %u, expected %u", g.fam, fm ? (unsigned)fm->getClassSize() : 0u, g.famSize);
			ok = false; break;
		}
		if (!g.ourMeta || !size_ok((uint32_t)g.ourMeta->getClassSize(), g.ourSize)) { GARNET_LOG("layout FAIL class %s: own size mismatch", g.ours); ok = false; break; }
		const GateResult r = gate_compare(g.ztvOurs + 2, g.ztvFam + 2, g.nslots, g.ovr, g.novr, lo, hi);   // slot 0 sits at the vtable symbol + 16
		if (r.v != kGateOk) {
			GARNET_LOG("layout FAIL class %s slot %u verdict %u ours %#llx family %#llx", g.ours, r.slot, (unsigned)r.v, (unsigned long long)r.ours, (unsigned long long)r.fam);
			ok = false; break;
		}
		total += r.compared;
		GARNET_LOG("layout %s vs %s: MATCH (%u slots, %u overrides, size %#x)", g.ours, g.fam, g.nslots, g.novr, g.famSize);
	}
	if (ok) GARNET_LOG("layout PASS %u/%u", total, want);
	OSCompareAndSwap(0, ok ? 1 : 2, &gGateState);
	return gGateState == 1;
}

// ---- ops acquisition -----------------------------------------------------------------------------------------------------------------------------
static const GarnetMetalOps *garnet_get_ops(IOService *nub) {
	if (!nub) return nullptr;
	const OSSymbol *fn = OSSymbol::withCString(GARNET_METAL_FN_SYMBOL);
	if (!fn) return nullptr;
	const GarnetMetalOps *o = nullptr;
	const IOReturn rc = nub->callPlatformFunction(fn, /*waitForFunction=*/false, (void *)&o, nullptr, nullptr, nullptr);
	fn->release();
	if (rc != kIOReturnSuccess) { GARNET_LOG("ops: callPlatformFunction rc %#x", (unsigned)rc); return nullptr; }
	const OpsVerdict v = ops_check(o);
	if (v != kOpsOk) { GARNET_LOG("ops: refused (verdict %u)", (unsigned)v); return nullptr; }
	return o;
}
static bool garnet_provider_is_nub(IOService *p) {
	const OSMetaClass *mc = p ? p->getMetaClass() : nullptr;
	const char *nm = mc ? mc->getClassName() : nullptr;
	if (!nm) return false;
	const char *want = GARNET_METAL_NUB_CLASS;
	for (; *want; ++want, ++nm) if (*want != *nm) return false;
	return *nm == 0;
}

// ---- GarnetAccelerator ------------------------------------------------------------------------------------------------------------------------
IOService *GarnetAccelerator::probe(IOService *provider, SInt32 *score) {
	GARNET_AUX_ENTER(nullptr);
	if (!garnet_provider_is_nub(provider)) return nullptr;      // nub only: never a PCI device
	if (!garnet_layout_gate()) return nullptr;                  // fail closed
	const GarnetMetalOps *o = garnet_get_ops(provider);
	if (!o) return nullptr;
	// Static config check against the FAMILY'S OWN defaults, before anything can reach IOSurfaceRoot::updateLimits: run its initializeConfigStructure()
	// (a plain field initialiser; start() does it again) and the bring-up kext's populate hook on top; a non-zero result refuses the match.
	garnet_initCfg(this);
	uint8_t *cfg = (uint8_t *)this + 0xc88;
	if (o->populate_config(cfg, 0x90u) != 0) { GARNET_LOG("probe: config static check refused"); return nullptr; }
	gOps = o;
	garnet_trace(GARNET_TR_PROBE_OK, (uint64_t)(uintptr_t)this);
	return IOService::probe(provider, score);
}

bool GarnetAccelerator::start(IOService *provider) {
	GARNET_AUX_ENTER(false);
	if (!gOps || !garnet_provider_is_nub(provider) || gGateState != 1) return false;   // probe did the work; never start unproven
	const bool ok = IOGraphicsAccelerator2::start(provider);
	if (ok) registerService();                                                     // AppleParavirtAccelerator::start does the same
	garnet_trace(GARNET_TR_STARTED, ok, (uint64_t)(uintptr_t)this);
	return ok;
}

void GarnetAccelerator::free() {
	if (ctx && gOps) { gOps->device_close(ctx); if (gCtx == ctx) gCtx = nullptr; ctx = nullptr; stampMD = nullptr; stampVA = nullptr; }   // idempotent; the family's stop normally got here first
	IOGraphicsAccelerator2::free();
}

bool GarnetAccelerator::configureDevice(IOPCIDevice *) {
	GARNET_AUX_ENTER(false);
	IOService *p = getProvider();
	if (!gOps || !p || !garnet_provider_is_nub(p) || ctx) return false;
	void *c = gOps->device_open(this, p);
	if (!c) return false;
	ctx = c; nub = p; gCtx = c;
	stampMD = (IOMemoryDescriptor *)gOps->stamp_memory(c, nullptr);
	stampVA = gOps->stamp_va(c);
	garnet_trace(GARNET_TR_DEVICE_OPEN, (uint64_t)(uintptr_t)c);
	if (!stampMD || !stampVA) { gOps->device_close(c); ctx = nullptr; gCtx = nullptr; stampMD = nullptr; stampVA = nullptr; return false; }
	return true;
}

void GarnetAccelerator::teardownDevice(IOPCIDevice *) {     // tolerates a NULL argument and a half-configured device
	if (ctx && gOps) { garnet_trace(GARNET_TR_DEVICE_CLOSE, (uint64_t)(uintptr_t)ctx); gOps->device_close(ctx); }
	ctx = nullptr; gCtx = nullptr; stampMD = nullptr; stampVA = nullptr;
}

static const char kFallbackName[] = "garnetaccel";   // a static NON-NULL name: IOAccelDevice2::get_name strncpy's cfg->name (a NULL name would fault)

void GarnetAccelerator::populateAccelConfig(IOAccelConfig *cfg) {
	GARNET_AUX_ENTER_V();
	uint8_t *c = (uint8_t *)cfg;
	const int rc = (gOps && cfg) ? gOps->populate_config(c, 0x90u) : -1;
	garnet_trace(GARNET_TR_POPULATE, (uint64_t)(int64_t)rc);
	if (!config_keep(gOps != nullptr, rc) && c) {
		// Fail closed WITHOUT a NULL name (validateConfigStructure is never called in start): keep the family defaults (non-zero IOSurface limits), a static name, and
		// tear the device down so the event machine's init finds no stamp VA and fails, which aborts the family's start.
		const uint64_t np = (uint64_t)(uintptr_t)kFallbackName;
		for (int i = 0; i < 8; ++i) c[i] = (uint8_t)(np >> (8 * i));
		if (ctx && gOps) { gOps->device_close(ctx); }
		if (gCtx == ctx) gCtx = nullptr;
		ctx = nullptr; stampMD = nullptr; stampVA = nullptr;
	}
}

