// the generic virtual hook (GarnetMetalOps.h vhook): returns true when the bring-up kext handled the slot (*r = its return value)
static bool garnet_vhook(uint32_t cls, uint32_t slot, void *self, const uint64_t *a, uint32_t n, uint64_t *r) {
	if (!gOps || !gCtx || !gOps->vhook || !cap_has(gOps, GARNET_CAP_VHOOK)) return false;
	return gOps->vhook(gCtx, cls, slot, self, a, n, r) == 1;
}
