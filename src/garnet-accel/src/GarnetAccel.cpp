// ---- GarnetEventMachine -----------------------------------------------------------------------------------------------------------------------
bool GarnetEventMachine::init(IOGraphicsAccelerator2 *accel, unsigned int n, int timeout) {
	GARNET_AUX_ENTER(false);
	const bool sup = IOAccelEventMachineFast2::init(accel, n, timeout);          // FIRST (MUST-FIX 2)
	GarnetAccelerator *na = OSDynamicCast(GarnetAccelerator, accel);
	volatile uint32_t *va = na ? na->stampVA : nullptr;
	const EmPlan p = em_init_plan(sup, va != nullptr);
	if (p.ok) {
		typedef void (*SetStamp)(IOAccelEventMachine2 *, volatile uint32_t *);
		((SetStamp)(*(void ***)this)[38])(this, va);                               // slot 38 = setStampBaseAddress(unsigned volatile*), as paravirt's init does
	}
	garnet_trace(GARNET_TR_EM_INIT, p.ok, sup);
	return p.ok;
}

// ---- GarnetTask -------------------------------------------------------------------------------------------------------------------------------
// AppleParavirtTask::init (0x142b85b6): IORangeAllocator::init(size-1, 0x1000, 0x400, 0), allocateRange(0, 0x1000) (page 0 reserved), then
// IOAccelTask::init(accel, 1, &ra) and a release of whatever the callee left in ra.
bool GarnetTask::setup(IOGraphicsAccelerator2 *accel, uint32_t kind) {
	GARNET_AUX_ENTER(false);
	uint64_t size = 0, reserve = 0;
	if (!gOps || !gCtx || gOps->task_window(gCtx, kind, &size, &reserve) != 0 || !task_window_ok(size, reserve)) return false;
	IORangeAllocator *ra = IORangeAllocator::withRange((IORangeScalar)(size - 1), kPage, 0x400u, 0);
	if (!ra) return false;
	if (reserve && !ra->allocateRange(0, (IORangeScalar)reserve)) { ra->release(); return false; }
	const bool ok = garnet_IOAccelTask_init(this, accel, 1u, &ra);
	if (ra) ra->release();
	garnet_trace(GARNET_TR_TASK, kind, ok);
	return ok;
}

