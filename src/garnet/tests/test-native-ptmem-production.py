#!/usr/bin/env python3
# test-native-ptmem-production.py - extract production PtSnap+PtMem verbatim for the host test.
#   test-native-ptmem-production.py /scratch/native_ptmem_actual.inc [native_s1c.cpp]
# Extracts from `struct PtSnap {` to `// Return a session's page-table blocks` (exclusive)
# precisely, no hand copy. The C++ test #includes the output; stubs provide the real names
# (Session/VRAMAllocation/BringupContext/DeviceContext/GMCContext/gCtx/gPt/kArena*/pa_of_mc/
# RBAR0_64/WBAR0_64/bar0_memset_vram) at the boundary. Fails if the production text drifts
# (simplified snap, tail scrub, per-block quota) so the test cannot silently test a copy.
import sys
import argparse
from pathlib import Path

def main():
    parser = argparse.ArgumentParser(description="Extract the production page-table allocator for host tests")
    parser.add_argument("output", type=Path, help="generated include in the scratch build directory")
    parser.add_argument("source", nargs="?", type=Path)
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[3]
    src = args.source or root / "src/garnet/src/amd/garnet_submit_internal.hpp"
    out = args.output
    s = src.read_text()
    start_marker = "struct PtSnap {"
    end_marker = "// Return a session's page-table blocks"
    si = s.find(start_marker)
    if si < 0:
        print(f"FAIL: {start_marker!r} not found in {src}")
        return 1
    ei = s.find(end_marker, si)
    if ei < 0:
        print(f"FAIL: {end_marker!r} not found after PtSnap in {src}")
        return 1
    frag = s[si:ei].rstrip() + "\n"
    out.write_text("// GENERATED by test-native-ptmem-production.py from garnet_submit_internal.hpp\n"
                   "// Range: `struct PtSnap {` .. `// Return a session's page-table blocks` (exclusive).\n"
                   "// Do not edit by hand; rerun the script.\n" + frag)
    print(f"wrote {out} ({len(frag.splitlines())} lines from {src.name})")
    return 0

if __name__ == "__main__":
    sys.exit(main())
