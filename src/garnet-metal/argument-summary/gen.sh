#!/bin/sh
# Regenerates garnet_argument_summary_spv.h from summary.comp.
set -eu
cd "$(dirname "$0")"

out=garnet_argument_summary_spv.h
spv=summary.comp.spv
tmp="$out.tmp"
trap 'rm -f "$spv" "$tmp"' EXIT HUP INT TERM

glslangValidator -V --target-env vulkan1.2 summary.comp -o "$spv"
spirv-val --target-env vulkan1.2 "$spv"

source_sha=$(sha256sum summary.comp | awk '{print $1}')
{
    echo "/* generated by argument-summary/gen.sh - do not edit */"
    echo "/* source: summary.comp sha256 $source_sha */"
    echo "#ifndef RDNA4_ARGUMENT_SUMMARY_SPV_H"
    echo "#define RDNA4_ARGUMENT_SUMMARY_SPV_H"
    echo
    echo "static const unsigned char rdna4_argument_summary_cs_spv[] __attribute__((aligned(4))) = {"
    xxd -i < "$spv"
    echo "};"
    echo "#define RDNA4_ARGUMENT_SUMMARY_CS_SPV_BYTES (sizeof rdna4_argument_summary_cs_spv)"
    echo
    echo "#endif"
} > "$tmp"
mv "$tmp" "$out"
